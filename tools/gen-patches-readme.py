#!/usr/bin/env python3
"""Regenerate patches/README.md from the patch series headers.

Writes a markdown table summarising every patch: number, scope, subject,
top-level files touched.

Usage:
    tools/gen-patches-readme.py           # writes patches/README.md
    tools/gen-patches-readme.py --check   # exits 1 if patches/README.md is stale
    tools/gen-patches-readme.py --stdout  # prints to stdout, doesn't touch the file
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from patches import load_series, repo_root


HEADER = """\
# Patch series — olg-eve

> Auto-generated by `tools/gen-patches-readme.py`. Do not hand-edit.

| #    | Scope | Subject | Files touched |
|------|-------|---------|---------------|
"""


def _files_summary(files: list[str], limit: int = 3) -> str:
    """Compact column: show up to `limit` files, then `+N more`."""
    if not files:
        return ""
    shown = files[:limit]
    out = ", ".join(f"`{f}`" for f in shown)
    if len(files) > limit:
        out += f" *(+{len(files) - limit} more)*"
    return out


def render() -> str:
    rows = []
    for p in load_series():
        rows.append(
            f"| {p.number:04d} | `{p.scope}` | {p.summary} | {_files_summary(p.files)} |"
        )
    return HEADER + "\n".join(rows) + "\n"


def main(argv: list[str]) -> int:
    out = render()
    target = repo_root() / "patches" / "README.md"

    if "--stdout" in argv:
        sys.stdout.write(out)
        return 0

    if "--check" in argv:
        if not target.is_file():
            print(f"missing: {target}", file=sys.stderr)
            return 1
        if target.read_text() != out:
            print(f"stale: {target} — run tools/gen-patches-readme.py", file=sys.stderr)
            return 1
        return 0

    target.write_text(out)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
